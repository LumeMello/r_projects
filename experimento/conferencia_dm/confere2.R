suppressMessages(source("IC_Common.R"))
m <- read.csv("comparacao_dm.csv")
fs <- sprintf("ARIMA_w%d_industrial_sensors_results_30pts.xlsx", 1:4)
err <- do.call(rbind, lapply(fs, readxl::read_excel, sheet = "Erros_Teste"))
E <- split(err$Error, paste(err$Series_ID, err$Scenario, err$Filter))
r <- t(sapply(seq_len(nrow(m)), function(j) {
  x <- dm_test_safe(E[[paste(m$Series_ID[j], m$Scenario[j], "non_filter")]], E[[paste(m$Series_ID[j], m$Scenario[j], m$Filter[j])]])
  c(stat = x$stat, p = x$p, h = x$h_used, ve = x$varestimator, note = x$note)
}))
st <- as.numeric(r[, "stat"]); p <- as.numeric(r[, "p"])
cat("h usado:", unique(r[, "h"]), "| estimador:", paste(names(table(r[, "ve"])), table(r[, "ve"]), collapse = ", "), "\n")
cat("Notas:\n"); print(table(r[, "note"], useNA = "ifany"))
cat("Igual ao acf antigo (linhas sem variancia negativa):", sum(abs(st - m$acf_stat)[m$acf_warn == 0] < 1e-9), "de", sum(m$acf_warn == 0), "\n")
cat("Significativos p<=0.05 por cenario:\n"); print(tapply(p <= 0.05, m$Scenario, sum))
w <- which(m$acf_warn == 1)
print(data.frame(m[w, c("Series_ID", "Scenario", "Filter")], antes_stat = m$DM_Stat_orig[w], antes_p = m$DM_Pvalue_orig[w], depois_stat = st[w], depois_p = p[w]), row.names = FALSE)
